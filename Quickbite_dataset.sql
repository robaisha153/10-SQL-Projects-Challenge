DROP SCHEMA IF EXISTS quickbite CASCADE;
CREATE SCHEMA quickbite;
SET search_path TO quickbite;

CREATE TABLE customers (
    customer_id    INTEGER PRIMARY KEY,
    customer_name  VARCHAR(50),
    city           VARCHAR(20),
    signup_date    DATE
);

CREATE TABLE riders (
    rider_id    INTEGER PRIMARY KEY,
    rider_name  VARCHAR(50),
    city        VARCHAR(20),
    join_date   DATE
);

CREATE TABLE orders (
    order_id          INTEGER PRIMARY KEY,
    customer_id       INTEGER REFERENCES customers (customer_id),
    rider_id          INTEGER REFERENCES riders (rider_id),
    order_time        TIMESTAMP,
    promised_minutes  INTEGER,       -- delivery time promised to the customer
    delivered_time    TIMESTAMP,     -- NULL when the order was cancelled
    order_status      VARCHAR(15),   -- 'delivered' or 'cancelled'
    promo_code        VARCHAR(15)    -- NULL when no promo was used
);

CREATE TABLE order_items (
    order_item_id  INTEGER PRIMARY KEY,
    order_id       INTEGER REFERENCES orders (order_id),
    item_name      VARCHAR(40),
    quantity       INTEGER,
    unit_price     INTEGER           -- price per unit in PKR
);

